"""Menu de opciones.

Muestra un menu de varias opciones."""

numero = int(input("Seleccione una opcion: "))

if numero == 1:
    print("Opcion 1")
elif numero == 2:
    print("Opcion 2")
elif numero == 3:
    print("Opcion 3")
elif numero == 4:
    print("Opcion 4")
else:
    print("La opcion no es valida")